public class For_16 {

	public static void main(String[] args) {
		
		for (int i = 1; i <= 20; i++) {
			
			if (i % 3 == 0) {
				
				System.out.println("Multiple of 3");
				
			} else if (i % 2 == 0) {
				
				System.out.println("Even");
				
			} else {
				
				System.out.println("Other");
			}
			
		}

	}

}