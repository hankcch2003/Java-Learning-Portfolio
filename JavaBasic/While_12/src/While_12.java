public class While_12 {

	public static void main(String[] args) {
		
		int i = 1;
		
		while (i <= 5) {
			
			if (i == 1) {
				
				System.out.println("One");
				
			} else if (i == 2) {
				
				System.out.println("Two");
				
			} else if (i == 3) {
				
				System.out.println("Three");
				
			} else {
				
				System.out.println("Other");
			}
			
			i++;
		}

	}

}