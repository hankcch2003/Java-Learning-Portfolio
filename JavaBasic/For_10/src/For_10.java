public class For_10 {

	public static void main(String[] args) {
		
		for (int i = 10; i >= 1; i = i - 2) {
			
			if (i > 5) {
				
				System.out.println("High");
				
			} else if (i == 5) {
				
				System.out.println("Five");
				
			} else {
				
				System.out.println("Low");
			}
			
		}

	}

}